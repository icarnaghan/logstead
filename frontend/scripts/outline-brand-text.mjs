// One-off, dev-only. Converts the logo wordmark and tagline to outlined paths
// using Inter Bold / SemiBold (SIL OFL, see docs/brand/fonts/LICENSE.txt), then
// writes src/assets/brand/{brand-paths.ts,logo.svg,logo-mark.svg}.
//
// Run from frontend/: node scripts/outline-brand-text.mjs
// Not part of `npm run build`. Output files are committed.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import opentype from "opentype.js";

const here = dirname(fileURLToPath(import.meta.url));
const fontsDir = resolve(here, "../../docs/brand/fonts");
const outDir = resolve(here, "../src/assets/brand");

const load = (name) => {
  const buf = readFileSync(resolve(fontsDir, name));
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
};
const bold = load("Inter-Bold.ttf");
const semibold = load("Inter-SemiBold.ttf");

// Original artwork (docs/brand/logo-source.svg): text group at translate(180, 96).
const WORDMARK = { text: "logstead", x: 180, y: 96, size: 62, spacing: -1.5, font: bold };
const TAGLINE = { text: "SCHEDULE E SIMPLIFIED", x: 184, y: 122, size: 13, spacing: 2, font: semibold };

const round = (n) => Math.round(n * 100) / 100;

function outline({ text, x, y, size, spacing, font }) {
  // opentype.js letterSpacing is expressed in em.
  const path = font.getPath(text, x, y, size, { kerning: true, letterSpacing: spacing / size });
  path.commands.forEach((c) => {
    for (const k of ["x", "y", "x1", "y1", "x2", "y2"]) if (k in c) c[k] = round(c[k]);
  });
  return { d: path.toPathData(2), box: path.getBoundingBox() };
}

const wordmark = outline(WORDMARK);
const tagline = outline(TAGLINE);

const rightEdge = Math.max(wordmark.box.x2, tagline.box.x2);
const PAD = 20;
const width = Math.ceil((rightEdge + PAD) / 10) * 10;
const LOCKUP_VIEWBOX = `0 0 ${width} 160`;
const MARK_VIEWBOX = "25 21 140 140";

const GRADIENTS = [
  { id: "house", x1: "0%", y1: "0%", x2: "100%", y2: "100%", from: "#F59E0B", to: "#EA580C" },
  { id: "bar1", x1: "0%", y1: "0%", x2: "0%", y2: "100%", from: "#F97316", to: "#EA580C" },
  { id: "bar2", x1: "0%", y1: "0%", x2: "0%", y2: "100%", from: "#FBBF24", to: "#D97706" },
  { id: "bar3", x1: "0%", y1: "0%", x2: "0%", y2: "100%", from: "#34D399", to: "#0F766E" },
];
const CHIMNEY_PATH = "M 46 54 L 46 36 L 58 36 L 58 44";
const HOUSE_PATH =
  "M 28 72 L 80 30 L 132 72 L 132 124 C 132 128 128 132 124 132 L 36 132 C 32 132 28 128 28 124 Z";
const BARS = [
  { x: 46, y: 94, width: 16, height: 30, rx: 4, gradient: "bar1" },
  { x: 72, y: 74, width: 16, height: 50, rx: 4, gradient: "bar2" },
  { x: 98, y: 54, width: 16, height: 70, rx: 4, gradient: "bar3" },
];
const MARK_TRANSLATE = "translate(15, 10)";

const ts = `// Generated by frontend/scripts/outline-brand-text.mjs. Do not edit by hand.
// Wordmark: Inter Bold 62px, letter spacing -1.5. Tagline: Inter SemiBold 13px, letter spacing 2.
// Font: Inter (SIL Open Font License 1.1). Text is outlined, so nothing depends on a runtime font.

export const LOCKUP_VIEWBOX = ${JSON.stringify(LOCKUP_VIEWBOX)};
export const LOCKUP_WIDTH = ${width};
export const LOCKUP_HEIGHT = 160;
export const MARK_VIEWBOX = ${JSON.stringify(MARK_VIEWBOX)};
/** Transform applied to the mark group in lockup and mark-only coordinates. */
export const MARK_TRANSFORM = ${JSON.stringify(MARK_TRANSLATE)};

export interface BrandGradient {
  id: string;
  x1: string;
  y1: string;
  x2: string;
  y2: string;
  from: string;
  to: string;
}
export interface BrandBar {
  x: number;
  y: number;
  width: number;
  height: number;
  rx: number;
  gradient: string;
}

/** Gradient ids are short names. Components must prefix them (for example with useId) to avoid collisions. */
export const GRADIENTS: readonly BrandGradient[] = ${JSON.stringify(GRADIENTS, null, 2)};

export const CHIMNEY_PATH = ${JSON.stringify(CHIMNEY_PATH)};
export const HOUSE_PATH = ${JSON.stringify(HOUSE_PATH)};
export const HOUSE_STROKE_WIDTH = 8;
export const BARS: readonly BrandBar[] = ${JSON.stringify(BARS, null, 2)};

export const WORDMARK_PATH =
  ${JSON.stringify(wordmark.d)};

export const TAGLINE_PATH =
  ${JSON.stringify(tagline.d)};
`;
writeFileSync(resolve(outDir, "brand-paths.ts"), ts);

const defs = GRADIENTS.map(
  (g) =>
    `    <linearGradient id="${g.id}-grad" x1="${g.x1}" y1="${g.y1}" x2="${g.x2}" y2="${g.y2}">\n` +
    `      <stop offset="0%" stop-color="${g.from}" />\n      <stop offset="100%" stop-color="${g.to}" />\n    </linearGradient>`,
).join("\n");
const mark =
  `  <g transform="${MARK_TRANSLATE}">\n` +
  `    <path d="${CHIMNEY_PATH}" fill="none" stroke="url(#house-grad)" stroke-width="8" stroke-linecap="round" stroke-linejoin="round" />\n` +
  `    <path d="${HOUSE_PATH}" fill="none" stroke="url(#house-grad)" stroke-width="8" stroke-linecap="round" stroke-linejoin="round" />\n` +
  BARS.map(
    (b) =>
      `    <rect x="${b.x}" y="${b.y}" width="${b.width}" height="${b.height}" rx="${b.rx}" fill="url(#${b.gradient}-grad)" />`,
  ).join("\n") +
  `\n  </g>`;

const lockupSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${LOCKUP_VIEWBOX}" width="${width}" height="160" role="img" aria-label="Logstead">
  <defs>
${defs}
  </defs>
${mark}
  <path d="${wordmark.d}" fill="currentColor" />
  <path d="${tagline.d}" fill="#0F766E" />
</svg>
`;
const markSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${MARK_VIEWBOX}" width="140" height="140" role="img" aria-label="Logstead">
  <defs>
${defs}
  </defs>
${mark}
</svg>
`;
writeFileSync(resolve(outDir, "logo.svg"), lockupSvg);
writeFileSync(resolve(outDir, "logo-mark.svg"), markSvg);

console.log("wordmark bbox", wordmark.box);
console.log("tagline bbox", tagline.box);
console.log("LOCKUP_VIEWBOX", LOCKUP_VIEWBOX);
